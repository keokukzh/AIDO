#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ControlMethod {
    NativeApi,
    Cli,
    McpPlugin,
    GeneratedAdapter,
    UiAutomation,
    VisionControl,
}

impl ControlMethod {
    pub fn as_str(&self) -> &'static str {
        match self {
            ControlMethod::NativeApi => "NativeApi",
            ControlMethod::Cli => "Cli",
            ControlMethod::McpPlugin => "McpPlugin",
            ControlMethod::GeneratedAdapter => "GeneratedAdapter",
            ControlMethod::UiAutomation => "UiAutomation",
            ControlMethod::VisionControl => "VisionControl",
        }
    }
}

impl std::str::FromStr for ControlMethod {
    type Err = AppIntelError;
    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s {
            "NativeApi" => Ok(ControlMethod::NativeApi),
            "Cli" => Ok(ControlMethod::Cli),
            "McpPlugin" => Ok(ControlMethod::McpPlugin),
            "GeneratedAdapter" => Ok(ControlMethod::GeneratedAdapter),
            "UiAutomation" => Ok(ControlMethod::UiAutomation),
            "VisionControl" => Ok(ControlMethod::VisionControl),
            other => serde_json::from_str(&format!("\"{}\"", other)).map_err(AppIntelError::Json),
        }
    }
}

