    fn cleanup_db(path: &Path) {
        let _ = std::fs::remove_file(path);
    }

    #[test]
    fn test_discover_and_persist_known_apps() {
        let (engine, db_path) = setup_test_engine();
        let gateway = PermissionGateway::new(AccessMode::StandardAccess, PrivacyMode::PrivateOffline);

        let apps = engine
            .discover_known_windows_apps(&gateway)
            .expect("Discovery failed");

        assert_eq!(apps.len(), 4, "Should discover exactly 4 apps");

        let app_ids: Vec<String> = apps.iter().map(|a| a.app_id.clone()).collect();
        assert!(app_ids.contains(&"docker-desktop".to_string()));
        assert!(app_ids.contains(&"cursor-ide".to_string()));
        assert!(app_ids.contains(&"lm-studio".to_string()));
        assert!(app_ids.contains(&"google-chrome".to_string()));

        // Inspect Docker Desktop entry
        let docker = apps.iter().find(|a| a.app_id == "docker-desktop").unwrap();
        assert_eq!(docker.preferred_control, ControlMethod::Cli);
        assert_eq!(docker.auth_required, "Keine");
        assert_eq!(docker.adapter_origin, AdapterOrigin::Official);
        assert!(docker.user_enabled);
        assert_eq!(docker.capabilities.len(), 4);

        let cap_ids: Vec<&str> = docker
            .capabilities
            .iter()
            .map(|c| c.capability_id.as_str())
            .collect();
        assert_eq!(
            cap_ids,
            vec!["open_app", "list_containers", "start_stop_container", "prune_volumes"]
        );

        // Verify SQLite persistence by re-reading with a fresh engine instance
        let engine_reopened = AppIntelligenceEngine::new(&db_path).expect("Reopen failed");
        let reloaded_apps = engine_reopened
            .list_registered_apps()
            .expect("Failed to list apps");
        assert_eq!(reloaded_apps.len(), 4);
        assert_eq!(reloaded_apps, apps);

        cleanup_db(&db_path);
    }

    #[test]
    fn test_toggle_user_enabled_checkbox() {
        let (engine, db_path) = setup_test_engine();
        let gateway = PermissionGateway::new(AccessMode::StandardAccess, PrivacyMode::PrivateOffline);

        engine
            .discover_known_windows_apps(&gateway)
            .expect("Discovery failed");

        // Initially enabled
        let docker = engine.get_app("docker-desktop").unwrap();
        assert!(docker.user_enabled);

        // Toggle to false (checkbox unchecked in installer)
        engine
            .set_app_enabled("docker-desktop", false)
            .expect("Disabling failed");
        let docker_disabled = engine.get_app("docker-desktop").unwrap();
        assert!(!docker_disabled.user_enabled);

        // Toggle back to true
        engine
            .set_app_enabled("docker-desktop", true)
            .expect("Enabling failed");
        let docker_enabled = engine.get_app("docker-desktop").unwrap();
        assert!(docker_enabled.user_enabled);

        // Non-existent app returns AppNotFound
        let err = engine.set_app_enabled("nonexistent-app", true);
        assert!(matches!(err, Err(AppIntelError::AppNotFound(_))));

        cleanup_db(&db_path);
    }

    #[test]
    fn test_verify_capability_risk_separation() {
        let (engine, db_path) = setup_test_engine();
        let gateway = PermissionGateway::new(AccessMode::StandardAccess, PrivacyMode::PrivateOffline);

        engine
            .discover_known_windows_apps(&gateway)
            .expect("Discovery failed");

        // Test 1: Low-risk capability without approval requirement ("open_app")
        let status_open = engine
            .verify_harmless_capability(&gateway, "docker-desktop", "open_app")
            .expect("Verify open_app failed");
        assert_eq!(
            status_open,
            VerificationStatus::Verified,
            "Low-risk unapproved capability should be Verified"
        );

        // Check persisted state in SQLite
        let docker_after_open = engine.get_app("docker-desktop").unwrap();
        let open_cap = docker_after_open
            .capabilities
            .iter()
            .find(|c| c.capability_id == "open_app")
            .unwrap();
        assert_eq!(open_cap.status, VerificationStatus::Verified);

        // Test 2: High-risk capability requiring approval ("prune_volumes")
        let status_prune = engine
            .verify_harmless_capability(&gateway, "docker-desktop", "prune_volumes")
            .expect("Verify prune_volumes failed");
        assert_eq!(
            status_prune,
            VerificationStatus::Restricted,
            "Approval-requiring capability should be Restricted"
        );

        // Check persisted state in SQLite
        let docker_after_prune = engine.get_app("docker-desktop").unwrap();
        let prune_cap = docker_after_prune
            .capabilities
            .iter()
            .find(|c| c.capability_id == "prune_volumes")
            .unwrap();
        assert_eq!(prune_cap.status, VerificationStatus::Restricted);

        // Test 3: CapabilityNotFound and AppNotFound
        let err_cap = engine.verify_harmless_capability(&gateway, "docker-desktop", "nonexistent_cap");
        assert!(matches!(err_cap, Err(AppIntelError::CapabilityNotFound(_, _))));

        let err_app = engine.verify_harmless_capability(&gateway, "nonexistent_app", "open_app");
        assert!(matches!(err_app, Err(AppIntelError::AppNotFound(_))));

        cleanup_db(&db_path);
    }

    #[test]
    fn test_read_only_gateway_allows_discovery_and_verification() {
        let (engine, db_path) = setup_test_engine();
        // Even in ReadOnly access mode, DiscoverApps and VerifyAppCapability are read-only
        let gateway = PermissionGateway::new(AccessMode::ReadOnly, PrivacyMode::PrivateOffline);

        let apps = engine.discover_known_windows_apps(&gateway);
        assert!(apps.is_ok(), "ReadOnly mode should permit app discovery");

        let verify_res = engine.verify_harmless_capability(&gateway, "google-chrome", "open_url");
        assert!(
            verify_res.is_ok(),
            "ReadOnly mode should permit capability verification"
        );
        assert_eq!(verify_res.unwrap(), VerificationStatus::Restricted);

        // Running discovery again preserves the restricted status and does not wipe it
        let rediscovery = engine.discover_known_windows_apps(&gateway).unwrap();
        let chrome = rediscovery.iter().find(|a| a.app_id == "google-chrome").unwrap();
        let url_cap = chrome.capabilities.iter().find(|c| c.capability_id == "open_url").unwrap();
        assert_eq!(url_cap.status, VerificationStatus::Restricted);

        cleanup_db(&db_path);
    }

