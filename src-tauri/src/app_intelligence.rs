        let (engine, db_path) = setup_test_engine();
        let gateway = PermissionGateway::new(AccessMode::StandardAccess, PrivacyMode::PrivateOffline);

        engine
            .synthesize_and_verify_unknown_app_adapter(
                &gateway,
                "custom-audio",
                "Audio Studio",
                "SoundLab",
                r"C:\Audio\studio.exe",
                true,
            )
            .expect("Synthesis failed");

        // Verify SQLite persistence
        let loaded = engine.get_app("custom-audio").expect("Failed to get synthesized app");
        assert_eq!(loaded.display_name, "Audio Studio");
        assert_eq!(loaded.capabilities.len(), 3);

        let probe_cap = loaded
            .capabilities
            .iter()
            .find(|c| c.capability_id == "probe_version_status")
            .unwrap();
