    #[test]
    fn synthesizes_evidence_backed_app_registry_entry_with_risk_levels() {
        let temp_dir = std::env::temp_dir().join(format!("aido_rea_syn_{}", uuid::Uuid::new_v4()));
        std::fs::create_dir_all(&temp_dir).expect("temp dir creation");
        let exe_path = temp_dir.join("my_gui.exe");

        let pe_bytes = create_test_pe_bytes(
            0x8664,
            2,
            &[".text", ".rsrc"],
            &["USER32.dll", "WS2_32.dll"],
            false,
        );
        std::fs::write(&exe_path, pe_bytes).expect("write test pe");

        let report = inspect_binary(&exe_path).expect("inspect binary");
        let bridge = ReaBridge::new();
        let entry = bridge.synthesize_app_entry(
            &report,
            "test-custom-gui",
            "Custom GUI Application",
            "Acme Devs",
        );

        assert_eq!(entry.app_id, "test-custom-gui");
        assert_eq!(entry.display_name, "Custom GUI Application");
        assert_eq!(entry.preferred_control, ControlMethod::UiAutomation);
        assert_eq!(entry.adapter_origin, AdapterOrigin::AutoGenerated);
        assert!(entry.user_enabled);

        for cap in &entry.capabilities {
            if cap.risk == RiskLevel::Low {
                assert!(!cap.requires_approval);
                assert_eq!(cap.status, VerificationStatus::Verified);
            } else {
                assert!(cap.requires_approval);
                assert_eq!(cap.status, VerificationStatus::Restricted);
            }
        }

        let _ = std::fs::remove_dir_all(&temp_dir);
    }
