/// Builds the Tauri ACL command manifest.
///
/// `cfg(debug_assertions)` inside this build script follows the build-script
/// crate, which Cargo still compiles with assertions during `cargo build --release`.
/// `PROFILE` is the package profile: `debug` for dev/test, `release` for
/// release, `test --release`, and bench (Cargo 1.83 reports bench as `release`).
/// That matches `cfg(debug_assertions)` on the desktop binary for the stock profiles.
#[cfg(feature = "desktop")]
fn emit_desktop_acl() {
    // Tauri globs every toml in this directory and does not delete stale files.
    // A debug build writes seed_demo_state.toml; a later release build must not
    // keep that permission in the ACL.
    let autogenerated = std::path::Path::new("permissions/autogenerated");
    if autogenerated.exists() {
        std::fs::remove_dir_all(autogenerated).unwrap_or_else(|error| {
            panic!(
                "Alte ACL-Rechte in {} konnten nicht geloescht werden: {error}",
                autogenerated.display()
            );
        });
    }
    let profile = std::env::var("PROFILE").unwrap_or_else(|_| {
        panic!("Cargo PROFILE fehlt. seed_demo_state darf nicht still in die ACL rutschen.");
    });
    let commands: &'static [&'static str] = match profile.as_str() {
        "release" => RELEASE_COMMANDS,
        "debug" => DEBUG_COMMANDS,
        other => panic!(
            "Unbekanntes Cargo-PROFILE `{other}`. Nur debug und release sind vorgesehen, damit seed_demo_state aus Release-ACLs bleibt."
        ),
    };
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(commands)),
    )
    .expect("AIDO desktop configuration could not be built");
}
