//! Source-level lock between the desktop command handler, the Tauri ACL manifest,
//! and the window that actually calls each command.
//!
//! Runs without the `desktop` feature: it only reads source files.
//!
//! `memory_forget` and `proactive_dismiss` are invoked from the frontend and
//! still stay out of every capability. Both change state without a one-time
//! approval token. `scan_projects_catalog` rewrites the project index under a
//! read-only gateway check and has no frontend caller. `seed_demo_state` writes
//! memory, is registered only in debug builds, and must not appear in a release ACL.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Component, Path, PathBuf};

/// Invoked by a window, but not granted: state changes without an approval token.
const WITHHELD_UNGATED: &[&str] = &["memory_forget", "proactive_dismiss"];

/// Registered, not invoked, not granted.
/// `scan_projects_catalog` writes the catalog without a token.
/// `seed_demo_state` writes memory and exists only on the debug handler.
const REGISTERED_WITHOUT_CALLER: &[&str] = &["scan_projects_catalog", "seed_demo_state"];

/// User-submitted setup form. It writes settings without a one-time token and
/// stays granted because the setup window is that form, not an agent proposal.
/// `chat` also stays granted for local inference. Its "vergiss …" branch deletes
/// memory without a token; that is a handler defect, not an extra ACL grant.
const ACKNOWLEDGED_FORM_WRITES: &[&str] = &["save_setup"];

#[test]
fn desktop_acl_stays_aligned_with_handlers_and_windows() {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let repo = normalize(manifest_dir.join(".."));
    let mut errors = Vec::new();

    let main_rs = read_text(&manifest_dir.join("src/desktop/main.rs"));
    let build_rs = read_text(&manifest_dir.join("build.rs"));
    let sensitive_rs = read_text(&manifest_dir.join("src/sensitive_actions.rs"));
    let conf = read_text(&manifest_dir.join("tauri.conf.json"));

    let (debug_handler, release_handler) = match handler_lists(&main_rs) {
        Ok(lists) => lists,
        Err(error) => {
            errors.push(error);
            (BTreeSet::new(), BTreeSet::new())
        }
    };
    let release_manifest = match const_str_array(&build_rs, "RELEASE_COMMANDS") {
        Ok(list) => list,
        Err(error) => {
            errors.push(error);
            BTreeSet::new()
        }
    };
    let debug_manifest = match const_str_array(&build_rs, "DEBUG_COMMANDS") {
        Ok(list) => list,
        Err(error) => {
            errors.push(error);
            BTreeSet::new()
        }
    };

    if release_handler != release_manifest {
        errors.push(format!(
            "Release-Handler und RELEASE_COMMANDS weichen ab.\n  nur Handler: {}\n  nur build.rs: {}",
            display_set(&release_handler - &release_manifest),
            display_set(&release_manifest - &release_handler)
        ));
    }
    if debug_handler != debug_manifest {
        errors.push(format!(
            "Debug-Handler und DEBUG_COMMANDS weichen ab.\n  nur Handler: {}\n  nur build.rs: {}",
            display_set(&debug_handler - &debug_manifest),
            display_set(&debug_manifest - &debug_handler)
        ));
    }
    let mut expected_debug = release_manifest.clone();
    expected_debug.insert("seed_demo_state".into());
    if debug_manifest != expected_debug {
        errors.push(
            "DEBUG_COMMANDS muss RELEASE_COMMANDS plus seed_demo_state sein. seed_demo_state darf in Release-ACLs nicht vorkommen.".into(),
        );
    }
    if release_manifest.contains("seed_demo_state") {
        errors.push("seed_demo_state steht in RELEASE_COMMANDS.".into());
    }
    let profile_gate = build_rs.split_whitespace().collect::<Vec<_>>().join(" ");
    if !profile_gate.contains("\"release\" => RELEASE_COMMANDS") {
        errors.push(
            "build.rs muss im Cargo-PROFILE release nur RELEASE_COMMANDS an die ACL geben.".into(),
        );
    }
    if !profile_gate.contains("\"debug\" => DEBUG_COMMANDS") {
        errors.push("build.rs muss im Cargo-PROFILE debug DEBUG_COMMANDS an die ACL geben.".into());
    }
    if !profile_gate.contains("permissions/autogenerated")
        || !profile_gate.contains("remove_dir_all")
    {
        errors.push(
            "build.rs muss permissions/autogenerated loeschen, sonst bleibt seed_demo_state aus einem Debug-Build in der Release-ACL."
                .into(),
        );
    }

    let windows = match window_entries(&conf) {
        Ok(windows) => windows,
        Err(error) => {
            errors.push(error);
            Vec::new()
        }
    };
    let capabilities = match load_capabilities(&manifest_dir.join("capabilities")) {
        Ok(capabilities) => capabilities,
        Err(error) => {
            errors.push(error);
            Vec::new()
        }
    };
    let execute_commands = match gated_execute_commands(&sensitive_rs) {
        Ok(commands) => commands,
        Err(error) => {
            errors.push(error);
            BTreeSet::new()
        }
    };

    let mut grants: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    let mut core_grants: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    let mut capability_count: BTreeMap<String, usize> = BTreeMap::new();
    let known_windows: BTreeSet<String> =
        windows.iter().map(|window| window.label.clone()).collect();

    for capability in &capabilities {
        for window in &capability.windows {
            if !known_windows.contains(window) {
                errors.push(format!(
                    "Capability `{}` nennt das Fenster `{window}`, das in tauri.conf.json fehlt.",
                    capability.identifier
                ));
            }
            *capability_count.entry(window.clone()).or_default() += 1;
            let (commands, core) =
                match split_permissions(&capability.permissions, &release_manifest) {
                    Ok(split) => split,
                    Err(error) => {
                        errors.push(format!("{} ({})", error, capability.identifier));
                        continue;
                    }
                };
            grants.entry(window.clone()).or_default().extend(commands);
            core_grants.entry(window.clone()).or_default().extend(core);
        }
    }

    for window in &windows {
        if capability_count.get(&window.label).copied().unwrap_or(0) == 0 {
            errors.push(format!(
                "Fenster `{}` aus tauri.conf.json hat keine Capability.",
                window.label
            ));
        } else if capability_count[&window.label] != 1 {
            errors.push(format!(
                "Fenster `{}` steht in {} Capabilities. Pro Fenster genau eine Capability.",
                window.label, capability_count[&window.label]
            ));
        }
    }

    let mut invoked_anywhere = BTreeSet::new();
    let mut granted_anywhere = BTreeSet::new();
    for commands in grants.values() {
        granted_anywhere.extend(commands.iter().cloned());
    }

    for window in &windows {
        let surface = match frontend_surface(&repo, window) {
            Ok(surface) => surface,
            Err(error) => {
                errors.push(format!("Fenster `{}`: {error}", window.label));
                continue;
            }
        };
        let mut invoked = surface.commands;
        if surface.dynamic_execute && invoked.contains("get_active_proposals") {
            invoked.extend(execute_commands.iter().cloned());
        }
        invoked_anywhere.extend(invoked.iter().cloned());

        let mut expected = invoked.clone();
        for withheld in WITHHELD_UNGATED {
            expected.remove(*withheld);
        }
        let granted = grants.get(&window.label).cloned().unwrap_or_default();
        if granted != expected {
            errors.push(format!(
                "Fenster `{}`: Capability und tatsaechliche Aufrufe weichen ab.\n  nur Capability: {}\n  nur Aufruf: {}",
                window.label,
                display_set(&granted - &expected),
                display_set(&expected - &granted)
            ));
        }

        let mut expected_core = BTreeSet::new();
        if surface.start_dragging {
            expected_core.insert("core:window:allow-start-dragging".to_string());
        }
        if surface.window_close {
            expected_core.insert("core:window:allow-close".to_string());
        }
        let core = core_grants.get(&window.label).cloned().unwrap_or_default();
        if core != expected_core {
            errors.push(format!(
                "Fenster `{}`: Core-Permissions weichen ab.\n  nur Capability: {}\n  nur Aufruf: {}",
                window.label,
                display_set(&core - &expected_core),
                display_set(&expected_core - &core)
            ));
        }
    }

    for command in WITHHELD_UNGATED {
        if !invoked_anywhere.contains(*command) {
            errors.push(format!(
                "`{command}` ist als ungegatter Mutator gesperrt, wird aber von keinem Fenster aufgerufen."
            ));
        }
        if granted_anywhere.contains(*command) {
            errors.push(format!(
                "`{command}` aendert Zustand ohne Einmal-Token und darf keiner Capability angehoeren."
            ));
        }
    }
    for command in REGISTERED_WITHOUT_CALLER {
        if invoked_anywhere.contains(*command) {
            errors.push(format!(
                "`{command}` wird aufgerufen, ist aber als befehllos registriert markiert."
            ));
        }
        if granted_anywhere.contains(*command) {
            errors.push(format!("`{command}` darf keiner Capability angehoeren."));
        }
    }
    for command in ACKNOWLEDGED_FORM_WRITES {
        if !invoked_anywhere.contains(*command) || !granted_anywhere.contains(*command) {
            errors.push(format!(
                "`{command}` ist die bereits freigegebene Nutzerform und muss beim aufrufenden Fenster bleiben."
            ));
        }
    }

    let mut accounted = granted_anywhere.clone();
    accounted.extend(
        WITHHELD_UNGATED
            .iter()
            .map(|command| (*command).to_string()),
    );
    for command in REGISTERED_WITHOUT_CALLER {
        if release_manifest.contains(*command) {
            accounted.insert((*command).to_string());
        }
    }
    if accounted != release_manifest {
        errors.push(format!(
            "Release-Manifest ist nicht durch Capabilities und die bewusst gesperrten Befehle abgedeckt.\n  nur Manifest: {}\n  nur abgedeckt: {}",
            display_set(&release_manifest - &accounted),
            display_set(&accounted - &release_manifest)
        ));
    }
    if granted_anywhere.contains("seed_demo_state") || capabilities_grant_seed(&capabilities) {
        errors.push("seed_demo_state darf in keiner Capability stehen.".into());
    }

    if !errors.is_empty() {
        panic!("ACL-Abgleich fehlgeschlagen:\n{}", errors.join("\n"));
    }
}

struct WindowEntry {
    label: String,
    url: String,
}

struct CapabilityEntry {
    identifier: String,
    windows: Vec<String>,
    permissions: Vec<String>,
}

struct FrontendSurface {
    commands: BTreeSet<String>,
    dynamic_execute: bool,
    start_dragging: bool,
    window_close: bool,
}

fn frontend_surface(repo: &Path, window: &WindowEntry) -> Result<FrontendSurface, String> {
    let html_path = repo.join(window.url.trim_start_matches('/'));
    let html = fs::read_to_string(&html_path)
        .map_err(|error| format!("HTML `{}` fehlt ({error}).", html_path.display()))?;
    let entries = script_entries(&html);
    if entries.is_empty() {
        return Err(format!(
            "`{}` hat kein TypeScript-Modul.",
            html_path.display()
        ));
    }
    let mut files = Vec::new();
    let mut seen = BTreeSet::new();
    for entry in entries {
        let path = normalize(repo.join(entry.trim_start_matches('/')));
        walk_module(&path, &mut files, &mut seen)?;
    }
    let mut surface = FrontendSurface {
        commands: BTreeSet::new(),
        dynamic_execute: false,
        start_dragging: false,
        window_close: false,
    };
    let mut dynamics = Vec::new();
    for (path, source) in &files {
        let stripped = strip_ts_comments(source);
        if stripped.contains("startDragging(") {
            surface.start_dragging = true;
        }
        if stripped.contains("getCurrentWindow().close(") {
            surface.window_close = true;
        }
        for argument in
            invoke_arguments(&stripped).map_err(|error| format!("{}: {error}", path.display()))?
        {
            match argument {
                InvokeArg::Literal(command) => {
                    surface.commands.insert(command);
                }
                InvokeArg::Dynamic(expression) => {
                    if expression.split('.').next_back() == Some("execute_command") {
                        surface.dynamic_execute = true;
                    } else {
                        dynamics.push((path.clone(), expression));
                    }
                }
            }
        }
    }
    for (path, expression) in dynamics {
        if !is_ident(&expression) {
            return Err(format!(
                "{} ruft invoke({expression}) dynamisch auf. Der Test kann das nicht aufloesen.",
                path.display()
            ));
        }
        let resolved = resolve_param_commands(&files, &expression)?;
        if resolved.is_empty() {
            return Err(format!(
                "{} reicht `{expression}` an invoke weiter, ohne dass ein Aufruf ein Befehls-Literal setzt.",
                path.display()
            ));
        }
        surface.commands.extend(resolved);
    }
    Ok(surface)
}

fn walk_module(
    path: &Path,
    files: &mut Vec<(PathBuf, String)>,
    seen: &mut BTreeSet<PathBuf>,
) -> Result<(), String> {
    let path = normalize(path.to_path_buf());
    if !seen.insert(path.clone()) {
        return Ok(());
    }
    let source = fs::read_to_string(&path)
        .map_err(|error| format!("Modul `{}` fehlt ({error}).", path.display()))?;
    let stripped = strip_ts_comments(&source);
    let specs = relative_specifiers(&stripped);
    files.push((path.clone(), source));
    for spec in specs {
        if let Some(next) = resolve_specifier(&path, &spec)? {
            walk_module(&next, files, seen)?;
        }
    }
    Ok(())
}

fn resolve_specifier(from: &Path, spec: &str) -> Result<Option<PathBuf>, String> {
    let spec = spec.split('?').next().unwrap_or(spec);
    let raw = Path::new(spec);
    match raw.extension().and_then(|ext| ext.to_str()) {
        Some("css" | "svg" | "json" | "png" | "gif" | "webp") => return Ok(None),
        Some("ts" | "tsx") => {}
        Some("js" | "mjs") => {
            return Err(format!(
                "`{}` importiert `{spec}`. Der ACL-Test folgt nur TypeScript-Modulen.",
                from.display()
            ));
        }
        Some(other) => {
            return Err(format!(
                "`{}` importiert die unbekannte Datei `{spec}` (.{other}).",
                from.display()
            ));
        }
        None => {}
    }
    let base = from.parent().unwrap_or(Path::new(".")).join(raw);
    let candidate = if raw.extension().is_some() {
        base
    } else {
        base.with_extension("ts")
    };
    if candidate.is_file() {
        Ok(Some(normalize(candidate)))
    } else {
        Err(format!(
            "`{}` importiert `{spec}`, aber `{}` fehlt.",
            from.display(),
            candidate.display()
        ))
    }
}

fn script_entries(html: &str) -> Vec<String> {
    let mut entries = Vec::new();
    let mut rest = html;
    while let Some(index) = rest.find("<script") {
        rest = &rest[index + 7..];
        let end = rest.find('>').unwrap_or(rest.len());
        let tag = &rest[..end];
        rest = &rest[end..];
        if !tag.contains("type=\"module\"") && !tag.contains("type='module'") {
            continue;
        }
        if let Some(src) = attr_value(tag, "src") {
            if src.ends_with(".ts") || src.ends_with(".tsx") {
                entries.push(src);
            }
        }
    }
    entries
}

fn attr_value(tag: &str, name: &str) -> Option<String> {
    let needle = format!("{name}=");
    let index = tag.find(&needle)?;
    let after = tag[index + needle.len()..].trim_start();
    let quote = after.chars().next()?;
    if quote != '"' && quote != '\'' {
        return None;
    }
    let body = &after[quote.len_utf8()..];
    let end = body.find(quote)?;
    Some(body[..end].to_string())
}

enum InvokeArg {
    Literal(String),
    Dynamic(String),
}

fn invoke_arguments(source: &str) -> Result<Vec<InvokeArg>, String> {
    let mut found = Vec::new();
    let bytes = source.as_bytes();
    let mut index = 0;
    while index + 6 <= bytes.len() {
        if &bytes[index..index + 6] == b"invoke" && ident_boundary(source, index, index + 6) {
            let mut cursor = skip_ws(source, index + 6);
            if source[cursor..].starts_with('<') {
                cursor = skip_generic(source, cursor)?;
                cursor = skip_ws(source, cursor);
            }
            if source[cursor..].starts_with('(') {
                let args = paren_interior(source, cursor)?;
                let first = split_top_level(args)
                    .into_iter()
                    .next()
                    .unwrap_or("")
                    .trim();
                if first.starts_with('`') {
                    return Err("invoke mit Template-Literal ist nicht aufgeloest.".into());
                }
                if let Some(literal) = parse_quoted(first) {
                    if !is_command_name(&literal) {
                        return Err(format!("invoke-Literal `{literal}` ist kein Befehlsname."));
                    }
                    found.push(InvokeArg::Literal(literal));
                } else if !first.is_empty() {
                    found.push(InvokeArg::Dynamic(first.to_string()));
                }
            }
        }
        index = advance(source, index);
    }
    Ok(found)
}

fn resolve_param_commands(
    files: &[(PathBuf, String)],
    param: &str,
) -> Result<BTreeSet<String>, String> {
    let mut commands = BTreeSet::new();
    for (_, source) in files {
        let stripped = strip_ts_comments(source);
        for (name, params, body) in function_sigs(&stripped)? {
            let Some(position) = params.iter().position(|item| item == param) else {
                continue;
            };
            let forwards = invoke_arguments(&body)?.into_iter().any(|argument| {
                matches!(argument, InvokeArg::Dynamic(expression) if expression == param)
            });
            if !forwards {
                continue;
            }
            for (_, call_source) in files {
                let call_source = strip_ts_comments(call_source);
                for args in call_arguments(&call_source, &name)? {
                    let parts = split_top_level(&args);
                    if let Some(argument) = parts.get(position).copied().map(str::trim) {
                        if let Some(literal) = parse_quoted(argument) {
                            if !is_command_name(&literal) {
                                return Err(format!(
                                    "`{name}` bekommt `{literal}`, das ist kein Befehlsname."
                                ));
                            }
                            commands.insert(literal);
                        }
                    }
                }
            }
        }
    }
    Ok(commands)
}

fn function_sigs(source: &str) -> Result<Vec<(String, Vec<String>, String)>, String> {
    let bytes = source.as_bytes();
    let mut found = Vec::new();
    let mut index = 0;
    while index < bytes.len() {
        if source[index..].starts_with("function ") || looks_like_method(source, index) {
            if let Some(sig) = parse_signature(source, index)? {
                let next = sig.next;
                if next <= index {
                    return Err("Funktionsparser kommt nicht voran.".into());
                }
                index = next;
                found.push((sig.name, sig.params, sig.body));
                continue;
            }
        }
        index = advance(source, index);
    }
    Ok(found)
}

struct ParsedSig {
    name: String,
    params: Vec<String>,
    body: String,
    next: usize,
}

fn parse_signature(source: &str, index: usize) -> Result<Option<ParsedSig>, String> {
    let tail = &source[index..];
    let name_index = if tail.starts_with("function") {
        skip_ws(source, index + "function".len())
    } else {
        index
    };
    let Some(name) = read_ident(source, name_index) else {
        return Ok(None);
    };
    if is_ts_keyword(&name) {
        return Ok(None);
    }
    let after_name = skip_ws(source, name_index + name.len());
    if !source[after_name..].starts_with('(') {
        return Ok(None);
    }
    let params_raw = paren_interior(source, after_name)?;
    if !params_raw.contains(':') {
        return Ok(None);
    }
    let mut cursor = after_name + 1 + params_raw.len() + 1;
    cursor = skip_ws(source, cursor);
    if source[cursor..].starts_with(':') {
        cursor = match skip_type_annotation(source, cursor + 1) {
            Ok(cursor) => cursor,
            Err(_) => return Ok(None),
        };
    }
    cursor = skip_ws(source, cursor);
    if !source[cursor..].starts_with('{') {
        return Ok(None);
    }
    let body = brace_interior(source, cursor)?;
    let params = split_top_level(params_raw)
        .into_iter()
        .filter_map(|param| param_name(param.trim()))
        .collect();
    Ok(Some(ParsedSig {
        name,
        params,
        body: body.to_string(),
        next: cursor + 1 + body.len() + 1,
    }))
}

fn looks_like_method(source: &str, index: usize) -> bool {
    let at_start = index == 0 || !is_ident_char(source[..index].chars().next_back().unwrap_or(' '));
    if !at_start {
        return false;
    }
    let Some(name) = read_ident(source, index) else {
        return false;
    };
    if is_ts_keyword(&name) {
        return false;
    }
    let after = skip_ws(source, index + name.len());
    source[after..].starts_with('(')
}

fn param_name(param: &str) -> Option<String> {
    let param = param.trim().trim_start_matches("...");
    if param.is_empty() || param.starts_with('{') || param.starts_with('[') {
        return None;
    }
    let head = param.split(':').next().unwrap_or("").trim();
    let head = head.split('=').next().unwrap_or("").trim();
    let name = head.split_whitespace().last().unwrap_or("");
    if is_ident(name) && !is_ts_keyword(name) {
        Some(name.to_string())
    } else {
        None
    }
}

fn call_arguments(source: &str, name: &str) -> Result<Vec<String>, String> {
    let mut calls = Vec::new();
    let mut index = 0;
    while let Some(found) = source[index..].find(name) {
        let start = index + found;
        index = start + name.len();
        if !ident_boundary(source, start, index) {
            continue;
        }
        let cursor = skip_ws(source, index);
        if !source[cursor..].starts_with('(') {
            continue;
        }
        calls.push(paren_interior(source, cursor)?.to_string());
    }
    Ok(calls)
}

fn relative_specifiers(source: &str) -> Vec<String> {
    let mut specs = Vec::new();
    for keyword in ["from", "import"] {
        let mut index = 0;
        while let Some(found) = source[index..].find(keyword) {
            let start = index + found;
            index = start + keyword.len();
            if !ident_boundary(source, start, index) {
                continue;
            }
            let cursor = skip_ws(source, index);
            if let Some(spec) = quoted_at(source, cursor) {
                if spec.starts_with('.') {
                    specs.push(spec);
                }
            }
        }
    }
    specs
}

fn window_entries(conf: &str) -> Result<Vec<WindowEntry>, String> {
    let json = parse_json(conf)?;
    let windows = json
        .get("app")
        .and_then(|app| app.get("windows"))
        .and_then(Json::as_array)
        .ok_or("tauri.conf.json: app.windows fehlt.")?;
    let mut entries = Vec::new();
    for window in windows {
        let label = window
            .get("label")
            .and_then(Json::as_str)
            .ok_or("Ein Fenster hat kein label.")?
            .to_string();
        let url = window
            .get("url")
            .and_then(Json::as_str)
            .ok_or_else(|| format!("Fenster `{label}` hat keine url."))?
            .to_string();
        entries.push(WindowEntry { label, url });
    }
    if entries.is_empty() {
        return Err("tauri.conf.json definiert keine Fenster.".into());
    }
    Ok(entries)
}

fn load_capabilities(dir: &Path) -> Result<Vec<CapabilityEntry>, String> {
    let mut paths = fs::read_dir(dir)
        .map_err(|error| format!("capabilities fehlt ({error})."))?
        .map(|entry| entry.map(|entry| entry.path()))
        .collect::<Result<Vec<_>, _>>()
        .map_err(|error| format!("capabilities ist nicht lesbar ({error})."))?;
    paths.sort();
    let mut capabilities = Vec::new();
    for path in paths {
        if path.extension().and_then(|ext| ext.to_str()) != Some("json") {
            continue;
        }
        let text = read_text(&path);
        let json = parse_json(&text).map_err(|error| format!("{}: {error}", path.display()))?;
        let list = match &json {
            Json::Array(list) => list.clone(),
            Json::Object(_) => vec![json],
            _ => {
                return Err(format!(
                    "{} muss eine Capability oder eine Liste sein.",
                    path.display()
                ));
            }
        };
        for item in list {
            let identifier = item
                .get("identifier")
                .and_then(Json::as_str)
                .ok_or_else(|| format!("{} hat eine Capability ohne identifier.", path.display()))?
                .to_string();
            let windows =
                item.get("windows")
                    .and_then(Json::as_array)
                    .ok_or_else(|| format!("Capability `{identifier}` hat keine Fenster."))?
                    .iter()
                    .map(|window| {
                        window.as_str().map(str::to_string).ok_or_else(|| {
                            format!("Capability `{identifier}` hat kein Fenster-Label.")
                        })
                    })
                    .collect::<Result<Vec<_>, _>>()?;
            let permissions = item
                .get("permissions")
                .and_then(Json::as_array)
                .ok_or_else(|| format!("Capability `{identifier}` hat keine Permissions."))?
                .iter()
                .map(|permission| {
                    permission.as_str().map(str::to_string).ok_or_else(|| {
                        format!("Capability `{identifier}` darf nur String-Permissions enthalten.")
                    })
                })
                .collect::<Result<Vec<_>, _>>()?;
            capabilities.push(CapabilityEntry {
                identifier,
                windows,
                permissions,
            });
        }
    }
    if capabilities.is_empty() {
        return Err("Keine Capability-Datei gefunden.".into());
    }
    Ok(capabilities)
}

fn split_permissions(
    permissions: &[String],
    release_manifest: &BTreeSet<String>,
) -> Result<(BTreeSet<String>, BTreeSet<String>), String> {
    let mut commands = BTreeSet::new();
    let mut core = BTreeSet::new();
    for permission in permissions {
        if permission.starts_with("allow-") {
            let command = permission.trim_start_matches("allow-").replace('-', "_");
            if !release_manifest.contains(&command) {
                return Err(format!(
                    "Permission `{permission}` gehoert zu keinem Release-Befehl."
                ));
            }
            commands.insert(command);
        } else if permission.starts_with("core:") {
            core.insert(permission.clone());
        } else {
            return Err(format!("Unerwartete Permission `{permission}`."));
        }
    }
    Ok((commands, core))
}

fn capabilities_grant_seed(capabilities: &[CapabilityEntry]) -> bool {
    capabilities.iter().any(|capability| {
        capability.permissions.iter().any(|permission| {
            permission.contains("seed-demo-state") || permission.contains("seed_demo_state")
        })
    })
}

fn handler_lists(source: &str) -> Result<(BTreeSet<String>, BTreeSet<String>), String> {
    let mut debug = None;
    let mut release = None;
    let mut search_from = 0;
    while let Some(found) = source[search_from..].find("generate_handler!") {
        let start = search_from + found;
        search_from = start + "generate_handler!".len();
        let prelude = &source[start.saturating_sub(240)..start];
        let list = macro_idents(source, search_from)?;
        if prelude.contains("not(debug_assertions)") {
            if release.replace(list).is_some() {
                return Err("Mehr als ein Release-generate_handler!.".into());
            }
        } else if prelude.contains("cfg(debug_assertions)") {
            if debug.replace(list).is_some() {
                return Err("Mehr als ein Debug-generate_handler!.".into());
            }
        } else {
            return Err(
                "generate_handler! ohne cfg(debug_assertions) oder cfg(not(debug_assertions))."
                    .into(),
            );
        }
    }
    Ok((
        debug.ok_or("Debug-generate_handler! fehlt.")?,
        release.ok_or("Release-generate_handler! fehlt.")?,
    ))
}

fn macro_idents(source: &str, from: usize) -> Result<BTreeSet<String>, String> {
    let open = source[from..]
        .find('[')
        .ok_or("generate_handler! ohne [.")?
        + from;
    let body = bracket_interior(source, open)?;
    let mut names = BTreeSet::new();
    for part in body.split(',') {
        let name = part.split("//").next().unwrap_or("").trim();
        if name.is_empty() {
            continue;
        }
        if !is_command_name(name) {
            return Err(format!("Kein Befehlsname in generate_handler!: `{name}`."));
        }
        if !names.insert(name.to_string()) {
            return Err(format!("generate_handler! nennt `{name}` doppelt."));
        }
    }
    Ok(names)
}

fn const_str_array(source: &str, name: &str) -> Result<BTreeSet<String>, String> {
    let marker = format!("const {name}");
    let start = source
        .find(&marker)
        .ok_or_else(|| format!("build.rs definiert `{name}` nicht."))?;
    let open = source[start..]
        .find("= &[")
        .ok_or_else(|| format!("`{name}` ist kein Slice."))?
        + start
        + 3;
    let body = bracket_interior(source, open)?;
    let mut names = BTreeSet::new();
    let mut cursor = body;
    while let Some(start_quote) = cursor.find('"') {
        let literal = parse_rust_string(&cursor[start_quote..])?;
        if !is_command_name(&literal.value) {
            return Err(format!("`{name}` enthaelt `{}`.", literal.value));
        }
        if !names.insert(literal.value) {
            return Err(format!("`{name}` nennt einen Befehl doppelt."));
        }
        cursor = &cursor[start_quote + literal.consumed..];
    }
    Ok(names)
}

fn gated_execute_commands(source: &str) -> Result<BTreeSet<String>, String> {
    let marker = source
        .find("fn command_name")
        .ok_or("sensitive_actions.rs: fn command_name fehlt.")?;
    let open = source[marker..]
        .find('{')
        .ok_or("fn command_name ohne Koerper.")?
        + marker;
    let body = brace_interior(source, open)?;
    let mut commands = BTreeSet::new();
    let mut cursor = body;
    while let Some(start_quote) = cursor.find('"') {
        let literal = parse_rust_string(&cursor[start_quote..])?;
        if !literal.value.is_empty() {
            if !is_command_name(&literal.value) {
                return Err(format!(
                    "command_name liefert `{}`, das ist kein Befehlsname.",
                    literal.value
                ));
            }
            commands.insert(literal.value);
        }
        cursor = &cursor[start_quote + literal.consumed..];
    }
    if commands.is_empty() {
        return Err("command_name nennt keine Execute-Befehle.".into());
    }
    Ok(commands)
}

struct RustString {
    value: String,
    consumed: usize,
}

fn parse_rust_string(source: &str) -> Result<RustString, String> {
    let mut chars = source.char_indices();
    if chars.next().map(|(_, ch)| ch) != Some('"') {
        return Err("Rust-String erwartet.".into());
    }
    let mut value = String::new();
    let mut escaped = false;
    for (index, ch) in chars {
        if escaped {
            value.push(match ch {
                'n' => '\n',
                'r' => '\r',
                't' => '\t',
                '\\' => '\\',
                '"' => '"',
                other => other,
            });
            escaped = false;
            continue;
        }
        match ch {
            '\\' => escaped = true,
            '"' => {
                return Ok(RustString {
                    value,
                    consumed: index + ch.len_utf8(),
                });
            }
            other => value.push(other),
        }
    }
    Err("Rust-String nicht geschlossen.".into())
}

fn quoted_at(source: &str, index: usize) -> Option<String> {
    let quote = source[index..].chars().next()?;
    if quote != '"' && quote != '\'' {
        return None;
    }
    parse_js_string(&source[index..])
        .ok()
        .map(|literal| literal.value)
}

fn parse_quoted(text: &str) -> Option<String> {
    let trimmed = text.trim();
    if trimmed.starts_with('"') || trimmed.starts_with('\'') {
        parse_js_string(trimmed).ok().map(|literal| literal.value)
    } else {
        None
    }
}

struct JsString {
    value: String,
    #[allow(dead_code)]
    consumed: usize,
}

fn parse_js_string(source: &str) -> Result<JsString, String> {
    let mut chars = source.char_indices();
    let quote = chars
        .next()
        .map(|(_, ch)| ch)
        .ok_or("JS-String erwartet.")?;
    if quote != '"' && quote != '\'' {
        return Err("JS-String erwartet.".into());
    }
    let mut value = String::new();
    let mut escaped = false;
    for (index, ch) in chars {
        if escaped {
            value.push(match ch {
                'n' => '\n',
                'r' => '\r',
                't' => '\t',
                '\\' => '\\',
                '\'' => '\'',
                '"' => '"',
                other => other,
            });
            escaped = false;
            continue;
        }
        match ch {
            '\\' => escaped = true,
            ch if ch == quote => {
                return Ok(JsString {
                    value,
                    consumed: index + ch.len_utf8(),
                });
            }
            other => value.push(other),
        }
    }
    Err("JS-String nicht geschlossen.".into())
}

fn paren_interior(source: &str, open: usize) -> Result<&str, String> {
    interior(source, open, '(', ')')
}

fn bracket_interior(source: &str, open: usize) -> Result<&str, String> {
    interior(source, open, '[', ']')
}

fn brace_interior(source: &str, open: usize) -> Result<&str, String> {
    interior(source, open, '{', '}')
}

fn interior(source: &str, open: usize, left: char, right: char) -> Result<&str, String> {
    let bytes = source.as_bytes();
    if bytes.get(open).copied() != Some(left as u8) {
        return Err(format!("`{left}` erwartet."));
    }
    let mut depth = 1;
    let mut index = open + 1;
    let mut quote: Option<char> = None;
    let mut escaped = false;
    while index < bytes.len() {
        let ch = source[index..].chars().next().unwrap();
        let width = ch.len_utf8();
        if let Some(active) = quote {
            if escaped {
                escaped = false;
            } else if ch == '\\' {
                escaped = true;
            } else if ch == active {
                quote = None;
            }
        } else if ch == '"' || ch == '\'' || ch == '`' {
            quote = Some(ch);
        } else if ch == left {
            depth += 1;
        } else if ch == right {
            depth -= 1;
            if depth == 0 {
                return Ok(&source[open + 1..index]);
            }
        }
        index += width;
    }
    Err(format!("`{right}` fehlt."))
}

fn split_top_level(source: &str) -> Vec<&str> {
    let mut parts = Vec::new();
    let mut start = 0;
    let mut paren: i32 = 0;
    let mut bracket: i32 = 0;
    let mut brace: i32 = 0;
    let mut angle: i32 = 0;
    let mut quote: Option<char> = None;
    let mut escaped = false;
    for (index, ch) in source.char_indices() {
        if let Some(active) = quote {
            if escaped {
                escaped = false;
            } else if ch == '\\' {
                escaped = true;
            } else if ch == active {
                quote = None;
            }
            continue;
        }
        match ch {
            '"' | '\'' | '`' => quote = Some(ch),
            '(' => paren += 1,
            ')' => paren = paren.saturating_sub(1),
            '[' => bracket += 1,
            ']' => bracket = bracket.saturating_sub(1),
            '{' => brace += 1,
            '}' => brace = brace.saturating_sub(1),
            '<' => angle += 1,
            '>' => angle = angle.saturating_sub(1),
            ',' if paren == 0 && bracket == 0 && brace == 0 && angle == 0 => {
                parts.push(&source[start..index]);
                start = index + ch.len_utf8();
            }
            _ => {}
        }
    }
    if start <= source.len() {
        parts.push(&source[start..]);
    }
    parts
}

fn skip_generic(source: &str, open: usize) -> Result<usize, String> {
    let mut depth = 0;
    let mut quote: Option<char> = None;
    let mut escaped = false;
    for (index, ch) in source[open..].char_indices() {
        if let Some(active) = quote {
            if escaped {
                escaped = false;
            } else if ch == '\\' {
                escaped = true;
            } else if ch == active {
                quote = None;
            }
            continue;
        }
        match ch {
            '"' | '\'' | '`' => quote = Some(ch),
            '<' => depth += 1,
            '>' => {
                depth -= 1;
                if depth == 0 {
                    return Ok(open + index + ch.len_utf8());
                }
            }
            _ => {}
        }
    }
    Err("Generischer invoke-Typ ist nicht geschlossen.".into())
}

fn skip_type_annotation(source: &str, start: usize) -> Result<usize, String> {
    let mut paren: i32 = 0;
    let mut bracket: i32 = 0;
    let mut brace: i32 = 0;
    let mut angle: i32 = 0;
    let mut quote: Option<char> = None;
    let mut escaped = false;
    for (index, ch) in source[start..].char_indices() {
        if let Some(active) = quote {
            if escaped {
                escaped = false;
            } else if ch == '\\' {
                escaped = true;
            } else if ch == active {
                quote = None;
            }
            continue;
        }
        match ch {
            '"' | '\'' | '`' => quote = Some(ch),
            '(' => paren += 1,
            ')' => paren = paren.saturating_sub(1),
            '[' => bracket += 1,
            ']' => bracket = bracket.saturating_sub(1),
            '{' => {
                if paren == 0 && bracket == 0 && brace == 0 && angle == 0 {
                    return Ok(start + index);
                }
                brace += 1;
            }
            '}' => brace = brace.saturating_sub(1),
            '<' => angle += 1,
            '>' => angle = angle.saturating_sub(1),
            _ => {}
        }
    }
    Err("Rueckgabetyp ohne Funktionskoerper.".into())
}

fn strip_ts_comments(source: &str) -> String {
    let mut out = String::with_capacity(source.len());
    let mut chars = source.chars().peekable();
    while let Some(ch) = chars.next() {
        match ch {
            '"' | '\'' | '`' => {
                out.push(ch);
                let mut escaped = false;
                for inner in chars.by_ref() {
                    out.push(inner);
                    if escaped {
                        escaped = false;
                        continue;
                    }
                    if inner == '\\' {
                        escaped = true;
                        continue;
                    }
                    if inner == ch {
                        break;
                    }
                }
            }
            '/' if chars.peek() == Some(&'/') => {
                chars.next();
                for inner in chars.by_ref() {
                    if inner == '\n' {
                        out.push('\n');
                        break;
                    }
                }
            }
            '/' if chars.peek() == Some(&'*') => {
                chars.next();
                let mut previous = '\0';
                for inner in chars.by_ref() {
                    if previous == '*' && inner == '/' {
                        break;
                    }
                    previous = inner;
                }
                out.push(' ');
            }
            other => out.push(other),
        }
    }
    out
}

fn skip_ws(source: &str, mut index: usize) -> usize {
    while let Some(ch) = source[index..].chars().next() {
        if !ch.is_whitespace() {
            break;
        }
        index += ch.len_utf8();
    }
    index
}

fn advance(source: &str, index: usize) -> usize {
    match source[index..].chars().next() {
        Some(ch) => index + ch.len_utf8(),
        None => index + 1,
    }
}

fn read_ident(source: &str, index: usize) -> Option<String> {
    let mut name = String::new();
    for ch in source[index..].chars() {
        let ok = if name.is_empty() {
            ch == '_' || ch.is_ascii_alphabetic()
        } else {
            ch == '_' || ch.is_ascii_alphanumeric()
        };
        if !ok {
            break;
        }
        name.push(ch);
    }
    if name.is_empty() {
        None
    } else {
        Some(name)
    }
}

fn ident_boundary(source: &str, start: usize, end: usize) -> bool {
    let before_ok =
        start == 0 || !is_ident_char(source[..start].chars().next_back().unwrap_or(' '));
    let after_ok =
        end >= source.len() || !is_ident_char(source[end..].chars().next().unwrap_or(' '));
    before_ok && after_ok
}

fn is_ident_char(ch: char) -> bool {
    ch == '_' || ch == '$' || ch.is_ascii_alphanumeric()
}

fn is_ident(text: &str) -> bool {
    let mut chars = text.chars();
    match chars.next() {
        Some(ch) if ch == '_' || ch.is_ascii_alphabetic() => {}
        _ => return false,
    }
    chars.all(|ch| ch == '_' || ch.is_ascii_alphanumeric())
}

fn is_command_name(text: &str) -> bool {
    let mut chars = text.chars();
    match chars.next() {
        Some(ch) if ch.is_ascii_lowercase() => {}
        _ => return false,
    }
    chars.all(|ch| ch.is_ascii_lowercase() || ch.is_ascii_digit() || ch == '_')
}

