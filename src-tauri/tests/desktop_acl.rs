#[derive(Clone, Debug)]
#[allow(dead_code)]
enum Json {
    Null,
    Bool(bool),
    Number(String),
    String(String),
    Array(Vec<Json>),
    Object(Vec<(String, Json)>),
}

impl Json {
    fn get(&self, key: &str) -> Option<&Json> {
        match self {
            Json::Object(entries) => entries
                .iter()
                .find(|(name, _)| name == key)
                .map(|(_, value)| value),
            _ => None,
        }
    }

    fn as_array(&self) -> Option<&[Json]> {
        match self {
            Json::Array(items) => Some(items),
            _ => None,
        }
    }

    fn as_str(&self) -> Option<&str> {
        match self {
            Json::String(value) => Some(value),
            _ => None,
        }
    }
}

struct JsonParser<'a> {
    source: &'a [u8],
    index: usize,
}

fn parse_json(source: &str) -> Result<Json, String> {
    let mut parser = JsonParser {
        source: source.as_bytes(),
        index: 0,
    };
    parser.skip_ws();
    let value = parser.value()?;
    parser.skip_ws();
    if parser.index != parser.source.len() {
        return Err("JSON hat ueberschuessigen Text.".into());
    }
    Ok(value)
}

impl<'a> JsonParser<'a> {
    fn value(&mut self) -> Result<Json, String> {
        self.skip_ws();
        let ch = self.peek().ok_or("Unerwartetes JSON-Ende.")?;
        match ch {
            b'n' => self.consume_exact(b"null").map(|_| Json::Null),
            b't' => self.consume_exact(b"true").map(|_| Json::Bool(true)),
            b'f' => self.consume_exact(b"false").map(|_| Json::Bool(false)),
            b'"' => self.string().map(Json::String),
            b'[' => self.array(),
            b'{' => self.object(),
            b'-' | b'0'..=b'9' => self.number(),
            _ => Err(format!("Unerwartetes JSON-Zeichen `{}`.", ch as char)),
        }
    }

    fn array(&mut self) -> Result<Json, String> {
        self.bump(b'[')?;
        let mut items = Vec::new();
        self.skip_ws();
        if self.peek() == Some(b']') {
            self.bump(b']')?;
            return Ok(Json::Array(items));
        }
        loop {
            items.push(self.value()?);
            self.skip_ws();
            match self.peek() {
                Some(b',') => {
                    self.bump(b',')?;
                    self.skip_ws();
                }
                Some(b']') => {
                    self.bump(b']')?;
                    break;
                }
                _ => return Err("JSON-Array nicht geschlossen.".into()),
            }
        }
        Ok(Json::Array(items))
    }

    fn object(&mut self) -> Result<Json, String> {
        self.bump(b'{')?;
        let mut entries = Vec::new();
        self.skip_ws();
        if self.peek() == Some(b'}') {
            self.bump(b'}')?;
            return Ok(Json::Object(entries));
        }
        loop {
            self.skip_ws();
            if self.peek() != Some(b'"') {
                return Err("JSON-Schluessel erwartet.".into());
            }
            let key = self.string()?;
            self.skip_ws();
            self.bump(b':')?;
            let value = self.value()?;
            entries.push((key, value));
            self.skip_ws();
            match self.peek() {
                Some(b',') => {
                    self.bump(b',')?;
                }
                Some(b'}') => {
                    self.bump(b'}')?;
                    break;
                }
                _ => return Err("JSON-Objekt nicht geschlossen.".into()),
            }
        }
        Ok(Json::Object(entries))
    }

    fn string(&mut self) -> Result<String, String> {
        self.bump(b'"')?;
        let mut out = String::new();
        while let Some(ch) = self.peek() {
            match ch {
                b'"' => {
                    self.bump(b'"')?;
                    return Ok(out);
                }
                b'\\' => {
                    self.bump(b'\\')?;
                    let escaped = self.peek().ok_or("JSON-Escape abgeschnitten.")?;
                    self.bump(escaped)?;
                    match escaped {
                        b'"' => out.push('"'),
                        b'\\' => out.push('\\'),
                        b'/' => out.push('/'),
                        b'b' => out.push('\u{0008}'),
                        b'f' => out.push('\u{000c}'),
                        b'n' => out.push('\n'),
                        b'r' => out.push('\r'),
                        b't' => out.push('\t'),
                        b'u' => {
                            let mut hex = String::new();
                            for _ in 0..4 {
                                let digit = self.peek().ok_or("JSON-\\u abgeschnitten.")?;
                                self.bump(digit)?;
                                hex.push(digit as char);
                            }
                            let code = u32::from_str_radix(&hex, 16)
                                .map_err(|_| format!("JSON-\\u{hex} ist ungueltig."))?;
                            out.push(char::from_u32(code).ok_or("JSON-\\u ist kein Zeichen.")?);
                        }
                        _ => return Err("Unbekanntes JSON-Escape.".into()),
                    }
                }
                _ => {
                    let rest = std::str::from_utf8(&self.source[self.index..])
                        .map_err(|_| "Ungueltiges UTF-8 im JSON.")?;
                    let ch = rest
                        .chars()
                        .next()
                        .ok_or("JSON-String nicht geschlossen.")?;
                    out.push(ch);
                    self.index += ch.len_utf8();
                }
            }
        }
        Err("JSON-String nicht geschlossen.".into())
    }

    fn number(&mut self) -> Result<Json, String> {
        let start = self.index;
        if self.peek() == Some(b'-') {
            self.index += 1;
        }
        while matches!(
            self.peek(),
            Some(b'0'..=b'9' | b'.' | b'e' | b'E' | b'+' | b'-')
        ) {
            self.index += 1;
        }
        let text = std::str::from_utf8(&self.source[start..self.index])
            .map_err(|_| "Ungueltige JSON-Zahl.")?;
        Ok(Json::Number(text.to_string()))
    }

    fn consume_exact(&mut self, expected: &[u8]) -> Result<(), String> {
        if self.source[self.index..].starts_with(expected) {
            self.index += expected.len();
            Ok(())
        } else {
            Err(format!(
                "JSON erwartet {}.",
                std::str::from_utf8(expected).unwrap_or("Token")
            ))
        }
    }

    fn bump(&mut self, expected: u8) -> Result<(), String> {
        if self.peek() == Some(expected) {
            self.index += 1;
            Ok(())
        } else {
            Err(format!("JSON erwartet `{}`.", expected as char))
        }
    }

    fn skip_ws(&mut self) {
        while matches!(self.peek(), Some(b' ' | b'\n' | b'\r' | b'\t')) {
            self.index += 1;
        }
    }

    fn peek(&self) -> Option<u8> {
        self.source.get(self.index).copied()
    }
}
